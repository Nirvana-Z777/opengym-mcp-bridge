import { randomUUID } from 'node:crypto';
import { PlanError } from './errors.mjs';
import { only, text, integer, boundedOutput } from './validate.mjs';

// Interoperability vocabulary, verified against openGym v1.4.1. These are field
// values, not a bundled copy of upstream implementation or exercise data.
export const BODY_PARTS = ['back', 'cardio', 'chest', 'full body', 'lower arms', 'lower legs', 'neck', 'shoulders', 'upper arms', 'upper legs', 'waist'];
export const EQUIPMENT = ['assisted', 'band', 'barbell', 'bench', 'body weight', 'bosu ball', 'cable', 'clubbell', 'dumbbell', 'elliptical machine', 'ez barbell', 'hammer', 'kettlebell', 'landmine', 'leverage machine', 'macebell', 'medicine ball', 'olympic barbell', 'pull-up bar', 'resistance band', 'roller', 'rope', 'sandbag', 'skierg machine', 'sled machine', 'smith machine', 'stability ball', 'stationary bike', 'stepmill machine', 'suspension trainer', 'tire', 'trap bar', 'upper body ergometer', 'weight plate', 'weighted', 'wheel roller'];
export const MUSCLES = ['trapezius', 'deltoids', 'chest', 'upper-back', 'serratus', 'biceps', 'triceps', 'forearm', 'abs', 'obliques', 'lower-back', 'gluteal', 'quadriceps', 'hamstring', 'adductors', 'hip-flexors', 'calves', 'tibialis', 'cardiovascular system'];
const keyOf = name => name.normalize('NFKC').trim().replace(/\s+/g, ' ').toLocaleLowerCase('en');
function choice(value, allowed, label) {
  if (!allowed.includes(value)) throw new PlanError(`${label} is not in the allowed openGym vocabulary`);
  return value;
}
function muscles(value, label) {
  if (!Array.isArray(value) || value.length > MUSCLES.length || new Set(value).size !== value.length) throw new PlanError(`${label} must be a unique muscle list`);
  value.forEach(v => choice(v, MUSCLES, label));
  return [...value].sort((a, b) => MUSCLES.indexOf(a) - MUSCLES.indexOf(b));
}
export function publicCustom(exercise, state) {
  const str = v => typeof v==='string'?v:null;
  const strings = v => Array.isArray(v)?v.filter(x=>typeof x==='string'):[];
  return { exercise_id: str(exercise.id), name: str(exercise.n), body_part: str(exercise.bp), equipment: str(exercise.eq),
    primary_muscles: strings(exercise.primaries || (exercise.tg ? [exercise.tg] : [])), secondary_muscles: strings(exercise.secondaries || exercise.sm || []),
    description: str(exercise.desc) || '', reference_count: (state.routines || []).reduce((n, r) => n + (r.ex || []).filter(e => e.id === exercise.id).length, 0)
      + (state.workouts || []).reduce((n, w) => n + (w.entries || []).filter(e => e.id === exercise.id).length, 0) };
}
export function listCustom(state, input = {}) {
  only(input,['query','limit','offset']);
  const { query = '', limit = 50, offset = 0 } = input;
  text(query, 100, 'query', { empty: true }); integer(limit, 1, 100, 'limit'); integer(offset, 0, 100000, 'offset');
  const matches = (state.customEx || []).filter(e => !query || String(e.n || '').toLocaleLowerCase().includes(query.toLocaleLowerCase()));
  return boundedOutput({ exercises: matches.slice(offset, offset + limit).map(e => publicCustom(e, state)), total: matches.length,
    next_offset: offset + limit < matches.length ? offset + limit : null,
    allowed_values: { body_part: BODY_PARTS, equipment: EQUIPMENT, muscles: MUSCLES }, notes_are_untrusted: true });
}
export function changeCustomExercises(original, actions, catalogue) {
  if (!Array.isArray(actions) || actions.length < 1 || actions.length > 20) throw new PlanError('actions must contain 1-20 changes');
  const state = structuredClone(original);
  state.customEx ||= [];
  const changes = [], existing = [], created_ids = [], updated_ids = [];
  for (const action of actions) {
    only(action, ['type', 'exercise_id', 'name', 'body_part', 'equipment', 'primary_muscles', 'secondary_muscles', 'description'], 'custom exercise change');
    if (!['create', 'update'].includes(action.type)) throw new PlanError('Custom exercise deletion is not supported');
    if (action.type==='update') text(action.exercise_id,100,'exercise_id');
    const before = action.type === 'update' ? state.customEx.find(e => e.id === action.exercise_id) : null;
    if (action.type === 'update' && !before) throw new PlanError('Custom exercise not found', 'not-found');
    if (action.type === 'create' && action.exercise_id !== undefined) throw new PlanError('IDs are generated by the bridge');
    const next = before ? structuredClone(before) : { id: 'c' + randomUUID(), custom: true };
    if (!before || action.name !== undefined) next.n = text(action.name, 80, 'name');
    if (!before || action.body_part !== undefined) next.bp = choice(action.body_part, BODY_PARTS, 'body_part');
    if (!before || action.equipment !== undefined) next.eq = choice(action.equipment, EQUIPMENT, 'equipment');
    if (!before || action.description !== undefined) next.desc = text(action.description ?? '', 1000, 'description', { empty: true });
    if (!before || action.primary_muscles !== undefined || action.secondary_muscles !== undefined || (action.body_part === 'cardio' && before.bp !== 'cardio')) {
      const primaryInput = action.primary_muscles ?? before?.primaries ?? [];
      const primary = next.bp === 'cardio' ? ['cardiovascular system'] : muscles(primaryInput, 'primary_muscles');
      if (next.bp === 'cardio' && action.primary_muscles?.some(m => m !== 'cardiovascular system')) throw new PlanError('cardio uses cardiovascular system');
      const secondary = muscles(action.secondary_muscles ?? before?.secondaries ?? before?.sm ?? [], 'secondary_muscles');
      if (secondary.some(m => primary.includes(m))) throw new PlanError('Primary and secondary muscles must not overlap');
      next.primaries = primary; next.secondaries = secondary; next.sm = [...secondary]; next.muscleGroups = [...primary, ...secondary];
      next.tg = primary.includes(before?.tg) ? before.tg : primaryInput.find(m => primary.includes(m)) || primary[0] || '';
    }
    const renamed = !before || keyOf(next.n) !== keyOf(before.n);
    if (renamed) {
      if (!Object.keys(catalogue.exercises || {}).length) throw new PlanError('请先更新官方文字目录；仅名称的旧目录无法完整检查官方动作重复', 'catalogue-required');
      const candidates = [...state.customEx, ...Object.values(catalogue.exercises)];
      const duplicate = candidates.find(e => e.id !== before?.id && [e.n, catalogue.names?.[e.id]].some(n => typeof n === 'string' && keyOf(n) === keyOf(next.n)));
      if (duplicate) {
        if (before) throw new PlanError('动作名称已存在；请使用已有动作', 'duplicate');
        if (duplicate.bp !== next.bp || duplicate.eq !== next.eq) throw new PlanError('同名动作已存在但器材/部位不同；请核对后使用不同名称', 'duplicate');
        const existingPublic = publicCustom(duplicate,state), requestedPublic=publicCustom(next,state);
        for (const field of ['primary_muscles','secondary_muscles','description']) if (action[field]!==undefined
          && JSON.stringify(existingPublic[field])!==JSON.stringify(requestedPublic[field])) throw new PlanError('同名动作已存在，但所填肌群/说明不同；请先查看并明确更新已有动作', 'duplicate');
        existing.push(publicCustom(duplicate, state));
        continue;
      }
    }
    if (before) {
      state.customEx[state.customEx.indexOf(before)] = next;
      updated_ids.push(next.id);
    } else { state.customEx.push(next); created_ids.push(next.id); }
    changes.push({ type: action.type, exercise_id: next.id, before: before ? publicCustom(before, original) : null,
      after: publicCustom(next, state), preserved_media_and_unknown_fields: !!before });
  }
  return { state, details: boundedOutput({ changes, existing }), result: { created_ids, updated_ids, existing } };
}
